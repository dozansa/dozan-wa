#!/usr/bin/env bash
# Dozan WA — one-shot installer for a Huawei Cloud ECS (Ubuntu 22.04/24.04).
#
# Run from the root of the cloned repo:
#   sudo bash deploy/huawei/install.sh            (defaults to wa.dozan.sa)
#
# Re-running is safe: it keeps the existing .env (secrets) and just rebuilds/restarts.
set -euo pipefail

DOMAIN="${1:-wa.dozan.sa}"
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO_ROOT"

say()  { printf '\n\033[1;32m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31m!! %s\033[0m\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || fail "شغّل السكربت بـ sudo"
[[ -f docker-compose.yml ]] || fail "شغّل السكربت من داخل مجلد الريبو"

# ---------------------------------------------------------------- 1. Docker
if ! command -v docker >/dev/null 2>&1; then
  say "تثبيت Docker"
  apt-get update -y
  apt-get install -y ca-certificates curl gnupg
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /etc/apt/keyrings/docker.gpg
  chmod a+r /etc/apt/keyrings/docker.gpg
  . /etc/os-release
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
else
  say "Docker موجود: $(docker --version)"
fi

# ---------------------------------------------------------------- 2. Swap (build needs RAM)
MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
if [[ $MEM_MB -lt 3500 ]] && ! swapon --show | grep -q .; then
  say "الذاكرة ${MEM_MB}MB — إضافة 4GB swap للبناء"
  fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# ---------------------------------------------------------------- 3. .env
if [[ ! -f .env ]]; then
  [[ -n "$DOMAIN" ]] || fail "أول تشغيل يحتاج الدومين: sudo bash deploy/huawei/install.sh wa.dozan.sa"
  say "إنشاء .env بأسرار عشوائية"
  gen() { openssl rand -hex "$1"; }
  MASTER_KEY="$(gen 32)"
  cat > .env <<ENV
# ---- Dozan WA (generated by deploy/huawei/install.sh) ----
NODE_ENV=production
LOG_LEVEL=info
DOMAIN=${DOMAIN}
BASE_URL=https://${DOMAIN}
API_PORT=2785
TZ=Asia/Riyadh
AUTO_START_SESSIONS=true

DATABASE_TYPE=postgres
DATABASE_HOST=postgres
DATABASE_PORT=5432
DATABASE_NAME=openwa
DATABASE_USERNAME=openwa
DATABASE_PASSWORD=$(gen 24)
DATABASE_SYNCHRONIZE=false

API_MASTER_KEY=${MASTER_KEY}
API_KEY_PEPPER=$(gen 32)
ENV
  chmod 600 .env
  NEW_INSTALL=1
else
  say ".env موجود — أحتفظ بالأسرار الحالية"
  if [[ -n "$DOMAIN" ]]; then
    sed -i "s|^DOMAIN=.*|DOMAIN=${DOMAIN}|; s|^BASE_URL=.*|BASE_URL=https://${DOMAIN}|" .env
  fi
  NEW_INSTALL=0
fi
DOMAIN="$(grep '^DOMAIN=' .env | cut -d= -f2)"

# ---------------------------------------------------------------- 4. Firewall (ufw, if active)
if command -v ufw >/dev/null 2>&1 && ufw status | grep -q active; then
  ufw allow 80/tcp; ufw allow 443/tcp; ufw allow 443/udp
fi

# ---------------------------------------------------------------- 5. Build & start
say "البناء والتشغيل (أول مرة تاخذ 5–10 دقايق)"
COMPOSE=(docker compose -f docker-compose.yml -f deploy/huawei/docker-compose.huawei.yml --profile postgres)
"${COMPOSE[@]}" build --pull
"${COMPOSE[@]}" up -d

say "انتظار جاهزية الخدمة"
for i in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:2785/api/health/ready" >/dev/null 2>&1; then READY=1; break; fi
  sleep 5
done
[[ "${READY:-0}" == 1 ]] || { "${COMPOSE[@]}" logs --tail=80 openwa-api; fail "الخدمة ما جهزت — شوف السجل فوق"; }

# ---------------------------------------------------------------- 6. Summary
say "تم ✅"
echo "  الرابط:   https://${DOMAIN}"
if [[ "${NEW_INSTALL}" == 1 ]]; then
  echo "  مفتاح الدخول (ADMIN API Key) — احفظه الحين، ما يتكرر عرضه:"
  echo "    $(grep '^API_MASTER_KEY=' .env | cut -d= -f2)"
fi
echo
echo "  أوامر مفيدة:"
echo "    السجل:    ${COMPOSE[*]} logs -f openwa-api"
echo "    تحديث:    git pull && sudo bash deploy/huawei/install.sh"
echo "    إيقاف:    ${COMPOSE[*]} down"
